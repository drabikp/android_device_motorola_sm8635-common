#!/usr/bin/env python3
#
# Generate res/xml/vendor.xml, the per-carrier IMS settings (VoLTE, Wi-Fi calling,
# video calling, VoNR, RTT, supplementary services over UT) that Motorola ships
# for this phone.
#
# Why: VoLTE and Wi-Fi calling only appear when the carrier config sets
# carrier_volte_available_bool / carrier_wfc_ims_available_bool, and AOSP
# defaults both to false. AOSP CarrierConfig enables VoLTE for about 70 carriers.
# Stock reads Google CarrierSettings with Motorola's 3290 .pb files, which
# enable VoLTE for about 2200. The IMS stack itself works on this port; only the
# per-carrier half was missing.
#
# How: LineageOS's own converter (lineage/scripts/carriersettings-extractor)
# turns the stock .pb files into AOSP vendor.xml format. This script then keeps
# only the IMS keys, and only names that Android itself defines in
# CarrierConfigManager. That drops Motorola, MediaTek and Google app keys, and
# leaves data, APN and UI policy to AOSP's per-carrier files. CarrierConfig reads
# vendor.xml after those files (DefaultCarrierConfigService.loadConfig), so these
# values win for the keys they set and leave every other key alone.
#
# Usage, from the top of the tree:
#   device/motorola/sm8635-common/rro_overlays/CarrierConfigOverlay/generate-vendor-xml.py \
#       <stock dump>/product/etc/CarrierSettings
#
# Needs python3 protobuf (the extractor imports it).

import hashlib
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.abspath(os.path.join(HERE, "../../../../.."))
EXTRACTOR = os.path.join(TOP, "lineage/scripts/carriersettings-extractor/carriersettings_extractor.py")
CCM = os.path.join(TOP, "frameworks/base/telephony/java/android/telephony/CarrierConfigManager.java")
OUT = os.path.join(HERE, "res/xml/vendor.xml")

# IMS keys, matched against AOSP key names. The imsserviceentitlement group
# moves as a whole: ims_provisioning_bool without entitlement_server_url_string
# would require an entitlement check with nowhere to run it. This port ships
# ImsServiceEntitlement, as stock does.
IMS = re.compile(
    r"^(ims\.|imsvoice\.|imsvt\.|imswfc\.|imsss\.|imssms\.|imsrtt\.|imsemergency\."
    r"|imsserviceentitlement\.)"
    r"|volte|vowifi|wfc|vonr|rtt|_vt_|^vt_|video_call|video_conference|ims_|_ims"
    r"|enhanced_4g_lte|ss_over_ut|wifi_call|hd_audio|iwlan")

# Keys deliberately not taken from stock.
# hide_enhanced_4g_lte_bool: keep the VoLTE toggle visible, as this port decided
# when it first enabled VoLTE.
SKIP = {"hide_enhanced_4g_lte_bool"}


def aosp_keys():
    # KEY_X = "name", plus nested classes that build names from KEY_PREFIX.
    # Declarations are often wrapped across two lines, so scan the whole source
    # in order, tracking the KEY_PREFIX of the nested class being read.
    src = open(CCM).read()
    keys, prefix = set(), None
    decl = re.compile(r'KEY_PREFIX\s*=\s*"([a-z0-9_.]+)"'
                      r'|KEY_[A-Z0-9_]+\s*=\s*KEY_PREFIX\s*\+\s*"([a-z0-9_.]+)"'
                      r'|KEY_[A-Z0-9_]+\s*=\s*"([a-z0-9_.]+)"')
    for m in decl.finditer(src):
        if m.group(1):
            prefix = m.group(1)
        elif m.group(2):
            keys.add(prefix + m.group(2))
        else:
            keys.add(m.group(3))
    return keys


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__ or "usage: generate-vendor-xml.py <CarrierSettings dir>")
    src = sys.argv[1]
    pbs = sorted(f for f in os.listdir(src) if f.endswith(".pb"))
    digest = hashlib.sha256()
    for f in pbs:
        digest.update(f.encode())
        digest.update(open(os.path.join(src, f), "rb").read())

    known = aosp_keys()
    with tempfile.TemporaryDirectory() as tmp:
        # -v and -a name output FOLDERS (vendor.xml and apns-conf.xml are
        # written inside them); the APN list is not used here.
        subprocess.run([sys.executable, EXTRACTOR, "-i", src, "-v", tmp, "-a", tmp],
                       check=True)
        root = ET.parse(os.path.join(tmp, "vendor.xml")).getroot()

    blocks, kept_keys = 0, set()
    for cc in list(root):
        for item in list(cc):
            name = item.get("name", "")
            if name in SKIP or name not in known or not IMS.search(name):
                cc.remove(item)
            else:
                kept_keys.add(name)
        if len(cc) == 0:
            root.remove(cc)
        else:
            blocks += 1

    ET.indent(root, space="    ")
    body = ET.tostring(root, encoding="unicode")
    with open(OUT, "w") as out:
        out.write("<?xml version='1.0' encoding='utf-8'?>\n")
        out.write("<!-- GENERATED by generate-vendor-xml.py, do not edit by hand.\n")
        out.write(f"     Source: {len(pbs)} stock CarrierSettings .pb files (W1UXS36H),\n")
        out.write(f"     sha256 {digest.hexdigest()}.\n")
        out.write(f"     {blocks} carrier blocks, {len(kept_keys)} distinct IMS keys. -->\n")
        out.write(body)
        out.write("\n")
    print(f"{OUT}: {blocks} blocks, {len(kept_keys)} keys, from {len(pbs)} .pb files")


if __name__ == "__main__":
    main()
